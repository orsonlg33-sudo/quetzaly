export type TransactionType = 'expense' | 'income';
export type RateStatus = 'fetched' | 'estimated' | 'pending' | 'manual';

export interface FinanceEntry {
  id: string;
  type: TransactionType;
  /** Amount stored in integer cents (e.g., 14550 = $145.50) */
  amount: number;
  /** Currency code of the logged entry (e.g. 'MXN', 'USD') */
  currency: string;
  /** Equivalent amount in home currency in integer cents */
  homeAmount: number;
  /** Exchange rate from entry currency to home currency */
  rate: number;
  /** Status of the exchange rate */
  rateStatus: RateStatus;
  /** Whether the user manually edited this rate */
  rateEditedManually: boolean;
  /** Transaction date in YYYY-MM-DD format */
  date: string;
  /** Reference to Category id */
  categoryId: string;
  /** Optional notes */
  note?: string;
  /** Optional compressed receipt photo data URL */
  photoUrl?: string;
  /** Optional marker if loaded from sample test data */
  isSample?: boolean;
  createdAt: number;
  updatedAt: number;
  /** Recurring rule id if generated by a recurring rule */
  recurringId?: string;
  /** Occurrence date string YYYY-MM-DD if generated by a recurring rule */
  occurrenceDate?: string;
}

export type RecurringFrequency = 'weekly' | 'biweekly' | 'monthly' | 'yearly';

export interface RecurringRule {
  id: string;
  type: TransactionType;
  /** Amount in integer cents */
  amount: number;
  currency: string;
  categoryId: string;
  note?: string;
  frequency: RecurringFrequency;
  startDate: string; // YYYY-MM-DD
  endDate?: string; // YYYY-MM-DD (optional)
  active: boolean; // true = active, false = paused
  autoAdd: boolean; // default false
  monthlyDay?: number; // 1 to 31 for monthly rules
  createdAt: number;
  updatedAt: number;
  lastGeneratedDate?: string; // YYYY-MM-DD
}

export interface RecurringOccurrence {
  id: string; // `${ruleId}_${date}`
  ruleId: string;
  date: string; // YYYY-MM-DD
  status: 'posted' | 'skipped';
  entryId?: string;
  updatedAt: number;
}

export interface DueOccurrence {
  rule: RecurringRule;
  date: string; // YYYY-MM-DD
}

export interface Category {
  id: string;
  name: string;
  emoji: string;
  color: string;
  type: TransactionType;
  isArchived?: boolean;
  isDefault?: boolean;
  order?: number;
}

export interface UserSettings {
  homeCurrency: string;
  monthStartDay: number; // 1 to 31, default 22
  rolloverEnabled: boolean; // default false
  lastUsedCurrency: string;
  recentCurrencies?: string[]; // up to 4 most recently used currencies
  hasDismissedSamplePrompt?: boolean;
  themeMode?: 'light' | 'dark' | 'system';
  hasSeenWelcome?: boolean;
}

export interface BudgetPeriod {
  id: string;
  startDate: string; // YYYY-MM-DD
  endDate: string; // YYYY-MM-DD
  label: string;
  year: number;
  month: number; // 0-indexed month of cycle start
}

export interface PeriodSummary {
  period: BudgetPeriod;
  periodIncome: number; // in cents
  periodExpenses: number; // in cents
  periodBalance: number; // income - expenses in cents
  carriedOverBefore: number; // in cents
  effectiveStartingBalance: number; // carriedOverBefore if rolloverEnabled else 0
  totalAvailable: number; // effectiveStartingBalance + periodIncome
  netLeft: number; // totalAvailable - periodExpenses
  entryCount: number;
  pendingCount: number; // entries with rateStatus 'pending' waiting for a rate
}

export interface UndoAction {
  id: string;
  title: string;
  type: 'add' | 'edit' | 'delete';
  entry: FinanceEntry;
  entries?: FinanceEntry[]; // for batch operations (e.g. auto-added recurring entries)
  previousEntry?: FinanceEntry; // for edit undo
  timestamp: number;
}

export interface BudgetLimit {
  id: string;
  type: 'overall' | 'category';
  categoryId?: string; // undefined for overall budget limit
  periodId?: string; // undefined for repeating default; periodId for one-time period override
  amount: number; // in integer cents in home currency
  createdAt: number;
  updatedAt: number;
}
